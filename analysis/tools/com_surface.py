#!/usr/bin/env python3
"""com_surface.py — consolidated COM/registration surface of every module.

Purpose
-------
These modules do not import each other: they cooperate through COM class
objects, registry registration and RPC/UPnP protocols (see
``analysis/report/dependencies.md``, which records zero static inter-module
import edges).  The real "API map" therefore has three parts:

1. the COM types each module *implements* — recovered from its embedded MSFT
   type library (``analysis/tools/typelib.py``) and from its ATL registrar
   script resource (``REGISTRY`` payload, RGS text);
2. the GUIDs each module references as string or binary constants;
3. the export table (``DllGetClassObject`` & friends) that makes the module
   loadable as a COM server.

This tool joins those facts into one table per module and cross-checks them
against each other.

Usage
-----
    python3 analysis/tools/com_surface.py

Inputs (all generated by the other tools)
-----------------------------------------
* ``src/<module>/typelib/*.json`` — recovered type libraries
* ``analysis/report/data/resources.json`` — REGISTRY (RGS) resources
* ``analysis/report/data/strings/<module>.json`` — GUID string literals
* ``analysis/report/data/inventory.json`` — export tables

Outputs
-------
* ``analysis/report/data/com-surface.json``
* ``analysis/report/com-surface.md``

Limitations
-----------
* A GUID that appears only as a *binary* constant (16 bytes in ``.rdata``) is
  not attributed to a module here unless the type library or RGS names it; the
  binaries carry no symbolic names for such constants.
* Registration performed at run time by ``DllRegisterServer`` code paths that do
  not use an RGS script is not visible to this tool; those paths are covered by
  the decompiled ``DllRegisterServer`` implementations in ``src/<module>/``.
"""

from __future__ import annotations

import glob
import json
import os
import re

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
DATA = os.path.join(REPO, "analysis", "report", "data")
GUID_RE = re.compile(r"\{[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}\}")


def load(path, default):
    try:
        return json.load(open(path))
    except (OSError, ValueError):
        return default


def main() -> int:
    inv = load(os.path.join(DATA, "inventory.json"), {})
    resources = load(os.path.join(DATA, "resources.json"), {})
    records = {}
    for r in inv.get("files", []):
        slug = r.get("slug")
        if slug:
            rec = dict(r)
            pe = rec.get("pe") or {}
            rec["exports"] = pe.get("exports") or []
            rec["imports"] = pe.get("imports") or []
            records[slug] = rec

    # per-module RGS registrations and string-borne GUIDs
    rgs_by_module: dict[str, list[dict]] = {}
    for img in resources.get("images", []):
        slug = img["module"]
        for res in img.get("resources", []):
            if res["type"] == "REGISTRY" and res.get("decoded", {}).get("guids") is not None:
                rgs_by_module.setdefault(slug, []).append({
                    "resource_id": res["name"], "language": res["language"],
                    "script": res.get("extracted"),
                    "guids": res["decoded"].get("guids", []),
                    "bytes": res["decoded"].get("bytes"),
                    "statement_lines": res["decoded"].get("statement_lines"),
                })

    string_guids: dict[str, list[str]] = {}
    for path in sorted(glob.glob(os.path.join(DATA, "strings", "*.json"))):
        s = load(path, {})
        slug = s.get("module")
        if slug:
            string_guids[slug] = s.get("by_tag", {}).get("guid", [])

    tlb_slugs = {p.split(os.sep)[-3] for p in glob.glob(os.path.join(REPO, "src", "*", "typelib", "*.json"))}
    com_slugs = {sl for sl, r in records.items()
                 if any((e or {}).get("name", "").startswith("Dll")
                        for e in (r.get("exports") or []))}
    modules = []
    for slug in sorted(tlb_slugs | set(rgs_by_module) | com_slugs):
        tls = []
        for path in sorted(glob.glob(os.path.join(REPO, "src", slug, "typelib", "*.json"))):
            t = load(path, {})
            cc = t.get("guid_cross_check", {})
            tls.append({
                "library_guid": t.get("header", {}).get("library_guid"),
                "types": [{"kind": ty["kind"], "name": ty["name"], "guid": ty["guid"],
                           "methods": ty["member_counts"]["functions"],
                           "variables": ty["member_counts"]["variables"]} for ty in t.get("typeinfos", [])],
                "guid_cross_check": cc.get("summary"),
            })
        rec = records.get(slug, {})
        exports = [e.get("name") for e in rec.get("exports", []) if e.get("name")]
        modules.append({
            "module": slug,
            "artifact": rec.get("rel_path") or (f"bin/{slug}"),
            "com_server_exports": [e for e in exports if e and e.startswith("Dll")],
            "exports_total": len(exports),
            "type_libraries": tls,
            "registration_scripts": rgs_by_module.get(slug, []),
            "guid_string_literals": string_guids.get(slug, []),
        })

    # join/cross-check
    total_ifaces = sum(1 for m in modules for t in m["type_libraries"] for ty in t["types"]
                       if ty["kind"] in ("TKIND_INTERFACE", "TKIND_DISPATCH"))
    total_coclasses = sum(1 for m in modules for t in m["type_libraries"] for ty in t["types"]
                          if ty["kind"] == "TKIND_COCLASS")
    rgs_guids = {g for m in modules for r in m["registration_scripts"] for g in r["guids"]}
    tlb_guids = {ty["guid"] for m in modules for t in m["type_libraries"] for ty in t["types"] if ty["guid"]}
    out = {
        "generated_by": "analysis/tools/com_surface.py",
        "summary": {
            "modules": len(modules),
            "modules_with_type_library": sum(1 for m in modules if m["type_libraries"]),
            "modules_with_registration_script": sum(1 for m in modules if m["registration_scripts"]),
            "modules_with_com_exports": sum(1 for m in modules if m["com_server_exports"]),
            "interfaces_recovered": total_ifaces,
            "coclasses_recovered": total_coclasses,
            "guids_named_by_typelib": len(tlb_guids),
            "guids_named_by_rgs": len(rgs_guids),
            "guids_named_by_both": len(tlb_guids & rgs_guids),
            "rgs_only_guids": sorted(rgs_guids - tlb_guids),
            "typelib_only_guids": sorted(tlb_guids - rgs_guids),
        },
        "modules": modules,
    }
    os.makedirs(DATA, exist_ok=True)
    json.dump(out, open(os.path.join(DATA, "com-surface.json"), "w"), indent=1)
    open(os.path.join(REPO, "analysis", "report", "com-surface.md"), "w").write(render(out))
    s = out["summary"]
    print(f"[com] modules={s['modules']} typelibs={s['modules_with_type_library']} "
          f"rgs={s['modules_with_registration_script']} com_exports={s['modules_with_com_exports']} "
          f"interfaces={s['interfaces_recovered']} coclasses={s['coclasses_recovered']}")
    print(f"[com] GUIDs: typelib={s['guids_named_by_typelib']} rgs={s['guids_named_by_rgs']} "
          f"both={s['guids_named_by_both']} → analysis/report/com-surface.md")
    return 0


def render(out: dict) -> str:
    s = out["summary"]
    L = ["# COM / registration surface (generated)\n",
         "> Generated by `analysis/tools/com_surface.py` from the recovered type libraries, the",
         "> `REGISTRY` (ATL registrar) resources, the export tables and the GUID string literals.",
         "> Because the modules have **no** static imports between them, this table — not the PE",
         "> import graph — is the real inter-module interface map.\n",
         "## 1. Summary\n",
         f"* Modules covered: **{s['modules']}**; with an embedded type library: "
         f"**{s['modules_with_type_library']}**; with an ATL registrar script: "
         f"**{s['modules_with_registration_script']}**; exporting COM entry points: "
         f"**{s['modules_with_com_exports']}**.",
         f"* Recovered COM interfaces: **{s['interfaces_recovered']}**; coclasses: "
         f"**{s['coclasses_recovered']}**.",
         f"* GUIDs named by a type library: {s['guids_named_by_typelib']}; by a registrar script: "
         f"{s['guids_named_by_rgs']}; by both (independent agreement): "
         f"**{s['guids_named_by_both']}**.\n",
         "## 2. Per-module COM surface\n",
         "| Module | COM exports | Type library | Interfaces | Coclasses | RGS script | RGS GUIDs | GUID literals |",
         "|---|---|---|---|---|---|---|---|"]
    for m in out["modules"]:
        ifaces = sum(1 for t in m["type_libraries"] for ty in t["types"]
                     if ty["kind"] in ("TKIND_INTERFACE", "TKIND_DISPATCH"))
        ccls = sum(1 for t in m["type_libraries"] for ty in t["types"] if ty["kind"] == "TKIND_COCLASS")
        lib = ", ".join(f"`{t['library_guid']}`" for t in m["type_libraries"]) or "—"
        exports = ", ".join(f"`{e}`" for e in m["com_server_exports"]) or "—"
        rgs = ", ".join(f"id {r['resource_id']}" for r in m["registration_scripts"]) or "—"
        rgsg = len({g for r in m["registration_scripts"] for g in r["guids"]})
        L.append(f"| `{m['artifact'].split('/')[-1]}` | {exports} | {lib} | {ifaces} | {ccls} | "
                 f"{rgs} | {rgsg} | {len(m['guid_string_literals'])} |")
    L.append("\n## 3. Recovered interfaces and coclasses\n")
    L.append("| Module | Kind | Name | GUID | Methods | Variables |")
    L.append("|---|---|---|---|---|---|")
    for m in out["modules"]:
        for t in m["type_libraries"]:
            for ty in t["types"]:
                L.append(f"| `{m['artifact'].split('/')[-1]}` | {ty['kind'].replace('TKIND_','')} | "
                         f"`{ty['name']}` | `{ty['guid'] or '—'}` | {ty['methods']} | {ty['variables']} |")
    L.append("\n## 4. Registration scripts (`REGISTRY` resources)\n")
    for m in out["modules"]:
        for r in m["registration_scripts"]:
            L.append(f"* `{m['artifact'].split('/')[-1]}` id {r['resource_id']} ({r['language']}, "
                     f"{r['bytes']} B, {r['statement_lines']} statement lines) → `{r['script']}`")
            for g in r["guids"]:
                L.append(f"  * `{g}`")
    if s["rgs_only_guids"]:
        L.append("\n### GUIDs named only by a registrar script\n")
        for g in s["rgs_only_guids"]:
            L.append(f"* `{g}`")
    if s["typelib_only_guids"]:
        L.append("\n### GUIDs named only by a type library\n")
        for g in s["typelib_only_guids"]:
            L.append(f"* `{g}`")
    L.append("\n## 5. Cross-checks\n")
    for m in out["modules"]:
        for t in m["type_libraries"]:
            if t.get("guid_cross_check"):
                L.append(f"* `{m['artifact'].split('/')[-1]}`: {t['guid_cross_check']}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
